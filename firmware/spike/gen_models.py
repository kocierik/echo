# SPIKE ONLY: writes src/spike_models.h from the downloaded models before each build
import json
import os

Import("env")  # noqa: F821 (PlatformIO)

here = os.path.join(env.subst("$PROJECT_DIR"), "spike")  # noqa: F821
out = ["#pragma once", "// Generated by spike/gen_models.py: esphome/micro-wake-word-models v2, Apache-2.0"]
for name in ("hey_jarvis", "hey_mycroft", "okay_nabu"):
    data = open(os.path.join(here, name + ".tflite"), "rb").read()
    out.append(f"alignas(16) const unsigned char SPIKE_{name.upper()}[] = {{")
    out += ["  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    out.append("};")
open(os.path.join(env.subst("$PROJECT_DIR"), "src", "spike_models.h"), "w").write("\n".join(out) + "\n")  # noqa: F821
