/// An open task extracted from memory, shown on Today.
final class OpenTask {
  const OpenTask({
    required this.id,
    required this.name,
    this.dueDate,
    this.metadata = const {},
  });

  factory OpenTask.fromJson(Map<String, dynamic> json) {
    final rawMetadata = json['metadata_'];
    final metadata = rawMetadata is Map<String, dynamic>
        ? Map<String, dynamic>.unmodifiable(rawMetadata)
        : const <String, dynamic>{};
    final dueDate = metadata['due_date'];
    return OpenTask(
      id: json['id'] as String,
      name: (json['name'] as String? ?? '').trim(),
      dueDate: dueDate is String ? DateTime.tryParse(dueDate) : null,
      metadata: metadata,
    );
  }

  final String id;
  final String name;
  final DateTime? dueDate;

  /// Full entity metadata: the backend replaces it on update, so completing a
  /// task must send it back with `done: true`.
  final Map<String, dynamic> metadata;

  Map<String, dynamic> get completedMetadata => {...metadata, 'done': true};
}

/// The most recent daily digest generated by the backend.
final class DailySummary {
  const DailySummary({required this.date, required this.summary});

  factory DailySummary.fromJson(Map<String, dynamic> json) {
    return DailySummary(
      date: DateTime.parse(json['digest_date'] as String),
      summary: (json['summary'] as String? ?? '').trim(),
    );
  }

  final DateTime date;
  final String summary;
}
